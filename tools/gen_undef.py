#!/usr/bin/env python3
"""Regenerate the '#undef' safety net in hub.h.

The ESP32 core / xtensa / WiFi headers #define lots of short upper-case names (BR, LBEG, SAR ...). If the sketch declares a
constant with the same name the build breaks. hub.h therefore #undefs every upper-case name the sketch uses, right after the
system headers are included. Run this after adding games or constants:  python tools/gen_undef.py
"""
import glob, os, re
SK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware", "CydGameHub")
# names that are the sketch's own macros or intentional system symbols: never undefine these
KEEP = set("""RGB565 SCR_W SCR_H HUD_H PF_Y PF_H PIN_BACKLIGHT PIN_SPEAKER PIN_TOUCH_CLK PIN_TOUCH_CS PIN_TOUCH_MISO PIN_TOUCH_MOSI
INPUT_PULLUP LOW HIGH ESP_ARDUINO_VERSION_MAJOR ARDUINO_ARCH_ESP32 TL_DATUM TC_DATUM TR_DATUM ML_DATUM MC_DATUM MR_DATUM BL_DATUM BC_DATUM
BR_DATUM VSPI HSPI SPI G2048 WIFI_AP_STA WIFI_OFF WIFI_STA WL_CONNECTED HTTP_GET HTTP_POST HTTP_UPDATE_OK HTTP_UPDATE_FAILED
HTTP_UPDATE_NO_UPDATES HTTPC_STRICT_FOLLOW_REDIRECTS HTTP_CODE_OK
HUB_VERSION HUB_VARIANT HUB_BUILD UPDATE_BASE_URL WIFI_AUTH_OPEN""".split())
src = ""
for f in sorted(glob.glob(os.path.join(SK, "*.h")) + glob.glob(os.path.join(SK, "*.ino"))):
    if os.path.basename(f) == "version.h":
        continue
    t = open(f).read()
    t = t[:t.find("// BEGIN-UNDEF-NET")] + t[t.find("// END-UNDEF-NET"):] if "BEGIN-UNDEF-NET" in t else t
    t = re.sub(r"//.*", "", t)
    t = re.sub(r'"[^"\n]*"', '""', t)
    src += t + "\n"
names = sorted(set(re.findall(r"\b[A-Z][A-Z0-9_]*\b", src)) - KEEP)
block = ("// BEGIN-UNDEF-NET (generated by tools/gen_undef.py - do not edit by hand)\n"
         "// ---- Safety net: system headers #define many short upper-case names (BR, LBEG, SAR, ...). Any that equals one of this\n"
         "// sketch's own constants would break the build, so drop them now that all system headers have been read.\n"
         "// (Undefining a name that is not defined is harmless.)\n"
         + "".join("#undef %s\n" % n for n in names) + "// END-UNDEF-NET")
hp = os.path.join(SK, "hub.h")
h = open(hp).read()
a, b = h.index("// BEGIN-UNDEF-NET"), h.index("// END-UNDEF-NET") + len("// END-UNDEF-NET")
open(hp, "w").write(h[:a] + block + h[b:])
print("undef net: %d names" % len(names))
